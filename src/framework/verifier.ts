/**
 * Run trust ladder in order: compile → lint → tests×2 → generated → judge-for-prose.
 * Stops on first failure and writes diagnosis artefact to .fence/verdicts/.
 * S-04 — diagnosis artefact before retry is mandatory.
 * S-12 — cheapest verify first; happy-path ~1.0-1.2×.
 */
export async function runTrustLadder(
  _projectRoot: string,
  _taskId: string,
): Promise<VerifyReport> {
  const tiers: TierResult[] = [];
  const ephemeralPath = ensureEphemeralSuite(_projectRoot);
  const includeGenerated = ephemeralPath !== null;

  // Ordered ladder — compile→lint→tests×2→generated→judge-for-prose-only
  const ladder: TrustTier[] = ["compile", "lint", "tests", "tests-x2"];
  if (includeGenerated) ladder.push("generated");
  // judge-for-prose is never auto-added — caller must opt in for prose tasks only
  // TODO: add "judge-for-prose" only when task is prose/docs (check task metadata)

  for (const tier of ladder) {
    // TODO: dispatch to real check per tier:
    //   compile → `tsc --noEmit` (byte-capped)
    //   lint    → `eslint .` or `biome check`
    //   tests   → `npm test` / `vitest run`
    //   tests-x2 → same as tests, second run — compare results for flake (GEM-11 trust ladder)
    //   generated → `vitest run tests/.fence-smoke.test.ts`
    // TODO: capture output to .fence/verdicts/<taskId>-<tier>.log (diagnosis artefact)
    // TODO: enforce byte cap on output (S-03 4KB pipe)
    const result: TierResult = {
      tier,
      passed: true, // stub
      durationMs: 0,
      outputPath: `${VERDICT_DIR}/${_taskId}-${tier}.log`,
    };
    tiers.push(result);
    if (!result.passed) break; // fail-fast — but artefact already written for diagnosis
  }

  return {
    taskId: _taskId,
    tiers,
    overall: tiers.every((t) => t.passed) ? "pass" : "fail",
    generatedEphemeral: includeGenerated,
  };
}

