import { mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { createHash } from "node:crypto";

const ROOT = resolve(import.meta.dir, "..");
const SRC = join(ROOT, "src");
const DIST = join(ROOT, "dist");

function listFiles(dir: string): string[] {
  const out: string[] = [];
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) {
      for (const sub of listFiles(full)) out.push(join(entry, sub));
    } else {
      out.push(entry);
    }
  }
  return out;
}

function sha256(content: string): string {
  return createHash("sha256").update(content).digest("hex");
}

function emitCliJs(): void {
  const cliTs = readFileSync(join(SRC, "cli.ts"), "utf8");
  // src/cli.ts is Node+bun hybrid (spawnSync bun + import.meta.dir). For npm compat,
  // emit a Node 20+ compatible JS shim that delegates to tools/install.ts via bun or node.
  // Keep src/cli.ts as authority — this is the publishable bin.
  const js = `#!/usr/bin/env node
// dist/cli.js — see src/cli.ts (authority). Generated by tools/generate.ts — do not edit.
import { spawnSync } from "node:child_process";
import { resolve, join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
const __dirname = (() => { try { return import.meta.dirname ?? dirname(fileURLToPath(import.meta.url)); } catch { return process.cwd(); } })();
const root = resolve(__dirname, "..");
// Prefer bun, fall back to node --loader (bun not required for validate/build, required for install)
const bunCheck = spawnSync("bun", ["--version"], { stdio: "ignore" });
const cmd = bunCheck.status === 0 ? "bun" : "node";
const args = bunCheck.status === 0
  ? [join(root, "tools", "install.ts"), ...process.argv.slice(2)]
  : ["--loader", "bun", join(root, "tools", "install.ts"), ...process.argv.slice(2)];
const result = spawnSync(cmd, args, { stdio: "inherit" });
process.exit(result.status ?? 0);
`;
  writeFileSync(join(DIST, "cli.js"), js, "utf8");
}

export function generate(): string[] {
  rmSync(DIST, { recursive: true, force: true });
  mkdirSync(DIST, { recursive: true });
  const report: string[] = [];
  const files = listFiles(SRC).sort();
  for (const file of files) {
    const from = join(SRC, file);
    const to = join(DIST, file);
    mkdirSync(join(to, ".."), { recursive: true });
    writeFileSync(to, readFileSync(from), "utf8");
  }
  emitCliJs();
  const distFiles = listFiles(DIST).sort();
  const digests = distFiles.map((f) => `${f} ${sha256(readFileSync(join(DIST, f), "utf8"))}`);
  writeFileSync(join(DIST, "PROVENANCE.md"), `# Provenance\n\nGenerated from src/ by tools/generate.ts. Do not edit.\n\n${digests.join("\n")}\n`, "utf8");
  report.push(`dist: ${distFiles.length} files from src/`);
  return report;
}

if (import.meta.main) {
  for (const line of generate()) console.log(line);
}
